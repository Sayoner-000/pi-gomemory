package installer

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// cbmPiExtensionMarker es la cabecera que `codebase-memory-mcp install` escribe
// en la extensión de Pi que registra sus tools sin prefijo (HCD-070).
const cbmPiExtensionMarker = "Generated by codebase-memory-mcp for pi"

// maxExtensionScan acota lo que se lee de cada extensión: la cabecera está al
// principio del archivo.
const maxExtensionScan = 4096

// CodemodePartialHint es el remedio para el estado parcial de codemode: Pi
// tiene `+codemode` sin el perfil híbrido en mcp.json, o al revés (HCD-070).
func CodemodePartialHint() string {
	return "Elige un modo: `pi-gomemory-setup codemode on` (híbrido: tools de protocolo directas y el resto por codemode) o `pi-gomemory-setup codemode off` (directo: retira +codemode)."
}

// DuplicateCodebaseMemoryExtensions devuelve las extensiones de Pi generadas
// por codebase-memory-mcp cuando mcp.json registra también el servidor
// `codebase-memory`: ambas exponen las mismas tools y Pi las ve dos veces.
// Solo lee; nunca modifica esos archivos, que no son de pi-gomemory.
func DuplicateCodebaseMemoryExtensions(piAgentDir string) ([]string, error) {
	registered, err := hasMCPServer(piAgentDir, "codebase-memory")
	if err != nil || !registered {
		return nil, err
	}
	dir := filepath.Join(piAgentDir, "extensions")
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var dups []string
	for _, e := range entries {
		switch filepath.Ext(e.Name()) {
		case ".ts", ".js", ".mjs", ".mts":
		default:
			continue
		}
		path := filepath.Join(dir, e.Name())
		if info, err := os.Stat(path); err != nil || !info.Mode().IsRegular() {
			continue
		}
		if head, err := readHead(path, maxExtensionScan); err == nil && bytes.Contains(head, []byte(cbmPiExtensionMarker)) {
			dups = append(dups, path)
		}
	}
	sort.Strings(dups)
	return dups, nil
}

func readHead(path string, n int64) ([]byte, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return io.ReadAll(io.LimitReader(f, n))
}

func hasMCPServer(piAgentDir, name string) (bool, error) {
	mcpPath, err := configTarget(filepath.Join(piAgentDir, "mcp.json"))
	if err != nil {
		return false, err
	}
	config, err := readJSONObject(mcpPath)
	if err != nil {
		return false, err
	}
	raw, ok := config["mcpServers"]
	if !ok {
		return false, nil
	}
	var servers map[string]json.RawMessage
	if err := json.Unmarshal(raw, &servers); err != nil {
		return false, fmt.Errorf("%s: mcpServers no es un objeto válido: %w", mcpPath, err)
	}
	_, ok = servers[name]
	return ok, nil
}

func duplicateExtensionsHint(dups []string) string {
	return fmt.Sprintf("%s registra las tools de codebase-memory sin prefijo y duplica el servidor MCP `codebase-memory`. Retíralo (rm %s) y, al reinstalar codebase-memory-mcp, usa `codebase-memory-mcp install --clients=<agentes sin pi>`. pi-gomemory no lo toca porque no es suyo.",
		strings.Join(dups, ", "), strings.Join(dups, " "))
}

// warnExposure avisa en install/update del estado parcial de codemode y de
// las tools de codebase-memory duplicadas. No cambia nada (HCD-070).
func warnExposure(piAgentDir string, w io.Writer) {
	if st, err := GetCodemodeStatus(piAgentDir); err == nil && st.Partial {
		fmt.Fprintf(w, "%s    ⚠ codemode parcial (settings=%v, mcp=%v): Pi expone las tools MCP directas y además codemode. %s%s\n",
			ColorWarning, st.SettingsEnabled, st.MCPEnabled, CodemodePartialHint(), ColorReset)
	}
	if dups, err := DuplicateCodebaseMemoryExtensions(piAgentDir); err == nil && len(dups) > 0 {
		fmt.Fprintf(w, "%s    ⚠ %s%s\n", ColorWarning, duplicateExtensionsHint(dups), ColorReset)
	}
}

// exposureDoctorItems resume para doctor cómo expone Pi las tools MCP.
func exposureDoctorItems(piAgentDir string) []CheckItem {
	var items []CheckItem
	if st, err := GetCodemodeStatus(piAgentDir); err != nil {
		items = append(items, CheckItem{Name: "Modo codemode", Status: "WARN", Details: err.Error()})
	} else {
		switch {
		case st.Enabled:
			items = append(items, CheckItem{Name: "Modo codemode", Status: "OK", Details: "híbrido (codemode on)"})
		case st.Partial:
			items = append(items, CheckItem{Name: "Modo codemode", Status: "WARN",
				Details: fmt.Sprintf("parcial (settings=%v, mcp=%v). %s", st.SettingsEnabled, st.MCPEnabled, CodemodePartialHint())})
		default:
			items = append(items, CheckItem{Name: "Modo codemode", Status: "OK", Details: "directo (codemode off)"})
		}
	}
	if dups, err := DuplicateCodebaseMemoryExtensions(piAgentDir); err != nil {
		items = append(items, CheckItem{Name: "Tools de codebase-memory", Status: "WARN", Details: err.Error()})
	} else if len(dups) > 0 {
		items = append(items, CheckItem{Name: "Tools de codebase-memory", Status: "WARN", Details: duplicateExtensionsHint(dups)})
	} else {
		items = append(items, CheckItem{Name: "Tools de codebase-memory", Status: "OK", Details: "sin extensiones que dupliquen el servidor MCP"})
	}
	return items
}
