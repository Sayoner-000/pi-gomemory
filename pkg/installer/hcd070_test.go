// cbmemHeader reproduce la cabecera que escribe `codebase-memory-mcp install`
// en la extensión de Pi que registra sus tools sin prefijo (HCD-070).
const cbmemHeader = "// codebase-memory-mcp:start\n// Generated by codebase-memory-mcp for pi.\nexport default function (pi) {}\n"

// Tarea 1: con +codemode ajeno y sin preferencia, install deja los MCP en
// directo (HCD-050) y avisa del estado parcial con el remedio.
func TestHCD070PartialWarning(t *testing.T) {
	// Desde HCD-071 el parcial solo aparece con codemode off elegido.
	t.Run("+codemode ajeno con codemode off avisa", func(t *testing.T) {
		opts := sandbox(t)
		writeFile(t, CodemodeStatePath(opts.HomeDir), `{"preference":"off"}`)
		writeFile(t, filepath.Join(opts.PiAgentDir, "settings.json"), `{"defaultTools":["+codemode"]}`)
		var out bytes.Buffer
		if err := applyCodemodeDefault(opts, &out); err != nil {
			t.Fatal(err)
		}
		got := out.String()
		for _, want := range []string{"parcial", "pi-gomemory-setup codemode on", "pi-gomemory-setup codemode off"} {
			if !strings.Contains(got, want) {
				t.Fatalf("falta %q en la salida de install:\n%s", want, got)
			}
		}
		if st, _ := GetCodemodeStatus(opts.PiAgentDir); !st.Partial {
			t.Fatalf("se esperaba estado parcial (no se toca +codemode ajeno): %+v", st)
		}
	})
	t.Run("modo directo limpio no avisa", func(t *testing.T) {
		opts := sandbox(t)
		if err := SetCodemodePreference(opts, false); err != nil {
			t.Fatal(err)
		}
		var out bytes.Buffer
		if err := applyCodemodeDefault(opts, &out); err != nil {
			t.Fatal(err)
		}
		if strings.Contains(out.String(), "parcial") {
			t.Fatalf("aviso de parcial sin estado parcial:\n%s", out.String())
		}
	})
	t.Run("codemode on explícito no avisa", func(t *testing.T) {
		opts := sandbox(t)
		if err := SetCodemodePreference(opts, true); err != nil {
			t.Fatal(err)
		}
		var out bytes.Buffer
		if err := applyCodemodeDefault(opts, &out); err != nil {
			t.Fatal(err)
		}
		if strings.Contains(out.String(), "parcial") {
			t.Fatalf("aviso de parcial con híbrido completo:\n%s", out.String())
		}
	})
	if h := CodemodePartialHint(); !strings.Contains(h, "codemode on") || !strings.Contains(h, "codemode off") {
		t.Fatalf("CodemodePartialHint sin remedio: %q", h)
	}
}

// Tarea 2: se detectan extensiones de codebase-memory-mcp que duplican el
// servidor MCP y install avisa sin tocarlas.
func TestHCD070DuplicateExtension(t *testing.T) {
	t.Run("detecta y avisa sin tocar el archivo", func(t *testing.T) {
		opts := sandbox(t)
		ext := filepath.Join(opts.PiAgentDir, "extensions", "cbmem.ts")
		writeFile(t, ext, cbmemHeader)
		writeFile(t, filepath.Join(opts.PiAgentDir, "extensions", "mia.ts"), "export default function (pi) {}\n")
		var out bytes.Buffer
		if err := applyCodemodeDefault(opts, &out); err != nil {
			t.Fatal(err)
		}
		dups, err := DuplicateCodebaseMemoryExtensions(opts.PiAgentDir)
		if err != nil {
			t.Fatal(err)
		}
		if len(dups) != 1 || dups[0] != ext {
			t.Fatalf("duplicados = %v, se esperaba [%s]", dups, ext)
		}
		got := out.String()
		for _, want := range []string{ext, "codebase-memory", "--clients"} {
			if !strings.Contains(got, want) {
				t.Fatalf("falta %q en el aviso de install:\n%s", want, got)
			}
		}
		if data, err := os.ReadFile(ext); err != nil || string(data) != cbmemHeader {
			t.Fatalf("install modificó la extensión ajena: %q, %v", data, err)
		}
	})
	t.Run("sin servidor MCP codebase-memory no hay duplicado", func(t *testing.T) {
		opts := sandbox(t)
		writeFile(t, filepath.Join(opts.PiAgentDir, "extensions", "cbmem.ts"), cbmemHeader)
		writeFile(t, filepath.Join(opts.PiAgentDir, "mcp.json"), `{"mcpServers":{"gomemory":{"command":"mem","args":["mcp"]}}}`)
		dups, err := DuplicateCodebaseMemoryExtensions(opts.PiAgentDir)
		if err != nil {
			t.Fatal(err)
		}
		if len(dups) != 0 {
			t.Fatalf("duplicado sin servidor MCP: %v", dups)
		}
	})
	t.Run("sin extensiones no falla", func(t *testing.T) {
		opts := sandbox(t)
		dups, err := DuplicateCodebaseMemoryExtensions(opts.PiAgentDir)
		if err != nil || len(dups) != 0 {
			t.Fatalf("dups=%v err=%v", dups, err)
		}
	})
}

// Tarea 3: doctor informa del modo codemode y de las tools duplicadas.
func TestHCD070Doctor(t *testing.T) {
	find := func(items []CheckItem, name string) CheckItem {
		t.Helper()
		for _, it := range items {
			if it.Name == name {
				return it
			}
		}
		t.Fatalf("doctor sin ítem %q: %+v", name, items)
		return CheckItem{}
	}
	t.Run("limpio", func(t *testing.T) {
		opts := sandbox(t)
		if err := SetCodemodePreference(opts, false); err != nil {
			t.Fatal(err)
		}
		if err := applyCodemodeDefault(opts, &bytes.Buffer{}); err != nil {
			t.Fatal(err)
		}
		items := exposureDoctorItems(opts.PiAgentDir)
		if it := find(items, "Modo codemode"); it.Status != "OK" || !strings.Contains(it.Details, "directo") {
			t.Fatalf("modo codemode: %+v", it)
		}
		if it := find(items, "Tools de codebase-memory"); it.Status != "OK" {
			t.Fatalf("tools de codebase-memory: %+v", it)
		}
	})
	t.Run("parcial y duplicado", func(t *testing.T) {
		opts := sandbox(t)
		writeFile(t, CodemodeStatePath(opts.HomeDir), `{"preference":"off"}`)
		writeFile(t, filepath.Join(opts.PiAgentDir, "settings.json"), `{"defaultTools":["+codemode"]}`)
		ext := filepath.Join(opts.PiAgentDir, "extensions", "cbmem.ts")
		writeFile(t, ext, cbmemHeader)
		if err := applyCodemodeDefault(opts, &bytes.Buffer{}); err != nil {
			t.Fatal(err)
		}
		items := exposureDoctorItems(opts.PiAgentDir)
		if it := find(items, "Modo codemode"); it.Status != "WARN" || !strings.Contains(it.Details, "codemode on") {
			t.Fatalf("modo codemode: %+v", it)
		}
		if it := find(items, "Tools de codebase-memory"); it.Status != "WARN" || !strings.Contains(it.Details, ext) {
			t.Fatalf("tools de codebase-memory: %+v", it)
		}
	})
	t.Run("híbrido", func(t *testing.T) {
		opts := sandbox(t)
		if err := SetCodemodePreference(opts, true); err != nil {
			t.Fatal(err)
		}
		if it := find(exposureDoctorItems(opts.PiAgentDir), "Modo codemode"); it.Status != "OK" || !strings.Contains(it.Details, "híbrido") {
			t.Fatalf("modo codemode: %+v", it)
		}
	})
}
